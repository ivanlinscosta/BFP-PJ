/** Supported business domains present in the semantic layer. */
export const SEMANTIC_DOMAINS = defineDomains([
  'media',
  'acquisition',
  'customer360',
  'products',
] satisfies readonly BusinessDomain[]);

export const METRIC_DEFINITION_BY_ID = new Map(METRIC_CATALOG.map((metric) => [metric.id, metric]));
export const DIMENSION_DEFINITION_BY_ID = new Map(
  DIMENSION_CATALOG.map((dimension) => [dimension.id, dimension]),
);
export const DATA_PRODUCT_BY_ID = new Map(
  DATA_PRODUCT_CATALOG.map((product) => [product.id, product]),
);
export const BUSINESS_TERM_BY_ID = new Map(BUSINESS_GLOSSARY.map((term) => [term.id, term]));

/** Returns a shallow copy of the supported semantic domains. */
export function listSemanticDomains(): BusinessDomain[] {
  return [...SEMANTIC_DOMAINS];
}

/** Looks up a governed metric by its stable semantic identifier. */
export function getMetricDefinition(id: string): GovernedMetricDefinition | undefined {
  return METRIC_DEFINITION_BY_ID.get(id);
}

/** Looks up a governed dimension by its stable semantic identifier. */
export function getDimensionDefinition(id: string): GovernedDimensionDefinition | undefined {
  return DIMENSION_DEFINITION_BY_ID.get(id);
}

/** Lists the governed metric catalog, optionally scoped to a single business domain. */
export function listMetricDefinitions(domain?: BusinessDomain): GovernedMetricDefinition[] {
  return domain ? METRIC_CATALOG.filter((metric) => metric.domain === domain) : [...METRIC_CATALOG];
}

/** Lists the governed dimension catalog, optionally scoped to a single business domain. */
export function listDimensionDefinitions(domain?: BusinessDomain): GovernedDimensionDefinition[] {
  return domain
    ? DIMENSION_CATALOG.filter((dimension) => dimension.domain === domain)
    : [...DIMENSION_CATALOG];
}

/** Checks whether a metric explicitly supports a given dimension. */
export function compatibility(metricId: string, dimensionId: string): boolean {
  const metric = getMetricDefinition(metricId);
  if (!metric) {
    return false;
  }

  if (metric.allowedDimensions === '*') {
    return true;
  }

  return metric.allowedDimensions.includes(dimensionId);
}

/** Utility set used by validation logic to detect temporal grouping requests. */
export const DATE_DIMENSION_IDS = new Set(
  DIMENSION_CATALOG.filter((dimension) => dimension.type === 'date').map(
    (dimension) => dimension.id,
  ),
);

/** Returns the governed data product that publishes a metric, when any. */
export function getDataProductForMetric(
  metricId: string,
): GovernedDataProductDefinition | undefined {
  return DATA_PRODUCT_CATALOG.find((product) =>
    (product.metricIds as readonly string[]).includes(metricId),
  );
}

/** Resolves a business-friendly label for a raw dimension value. */
export function resolveDimensionValueLabel(dimensionId: string, value: unknown): string {
  if (value === null || value === undefined || value === '') {
    return 'Não informado';
  }

  const raw = String(value);
  return getDimensionDefinition(dimensionId)?.valueLabels?.[raw] ?? raw;
}
