/** Typed reference to a real field from one of the governed dataset entities. */
export type SourceFieldRef = {
  [T in keyof DatasetEntityModelMap]: {
    entityType: T;
    field: Extract<keyof DatasetEntityModelMap[T], string>;
  };
}[keyof DatasetEntityModelMap];

/** Extra governance metadata carried by the semantic metric catalog. */
export type GovernedMetricDefinition = MetricDefinition & {
  baseEntity: DatasetEntityType;
  sourceFields: readonly SourceFieldRef[];
  category: string;
  tags: readonly string[];
  bakedFilters?: readonly {
    field: string;
    operator: FilterOperator;
    value?: unknown;
    reason: string;
  }[];
  supportsTemporalGrouping?: boolean;
  /** Highlighted in the curated data library of the playground. */
  featured?: boolean;
  /** Position in the curated data library. */
  libraryOrder?: number;
};

/** Extra governance metadata carried by the semantic dimension catalog. */
export interface GovernedDimensionDefinition extends DimensionDefinition {
  label: string;
  baseEntity: DatasetEntityType;
  sourceFields: readonly SourceFieldRef[];
  ordering: number;
  supportedGranularities?: readonly DateGranularity[];
  /** Highlighted in the curated data library of the playground. */
  featured?: boolean;
  /** Position in the curated data library. */
  libraryOrder?: number;
  /** Business-friendly labels for enumerated raw values. */
  valueLabels?: Readonly<Record<string, string>>;
}

/** Data product enriched with the starter semantic surface it exposes. */
export interface GovernedDataProductDefinition extends DataProductDefinition {
  metricIds: readonly string[];
  dimensionIds: readonly string[];
  /** Business-friendly name of the curated (Gold) dataset. */
  goldDataset: string;
  /** Physical Gold table registered in the Glue Data Catalog. */
  goldTable: string;
  /** Upstream business systems feeding the data product. */
  businessSources: readonly string[];
}

const fieldRef = <T extends keyof DatasetEntityModelMap>(
  entityType: T,
  field: Extract<keyof DatasetEntityModelMap[T], string>,
): SourceFieldRef => ({ entityType, field }) as unknown as SourceFieldRef;

